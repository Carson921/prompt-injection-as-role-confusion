def initialized_probabilities(signature,row_count,*,require_existing=False,readonly=False):
    expected=dict(signature=signature,rows=row_count,models=NAMES,classes=5,dtype='float32')
    marker=CACHE/'initialized.json';size=row_count*5*4
    paths={name:CACHE/f'{name}-probabilities.f32' for name in NAMES}
    if marker.exists():same(read(marker),expected,'Probability cache ownership')
    else:
        require(not (require_existing or readonly) and not any(path.exists() for path in paths.values())
            and not (CACHE/'progress.json').exists(),'Undeclared/missing probability ownership; refusing saved progress.')
        CACHE.mkdir(parents=True,exist_ok=True)
        for path in paths.values():
            array=np.memmap(path,mode='w+',dtype=np.float32,shape=(row_count,5));array[:]=np.nan;array.flush();del array
        data.atomic_json(marker,expected)
    require(all(path.is_file() and path.stat().st_size==size for path in paths.values()),
        'Probability file missing/truncated; refusing old cache/progress.')
    return {name:np.memmap(path,mode='r' if readonly else 'r+',dtype=np.float32,shape=(row_count,5)) for name,path in paths.items()}


def completed_indices(inputs,rows,next_batch):
    order=inputs.sort_values(['length','prompt_ix']).prompt_ix.to_numpy()
    require(type(next_batch) is int and 0<=next_batch<=(len(order)+BATCH_SIZE-1)//BATCH_SIZE,'Invalid deterministic batch cursor.')
    wanted=order[:min(len(order),next_batch*BATCH_SIZE)]
    return np.flatnonzero(rows.prompt_ix.isin(wanted).to_numpy())


def progress_record(signature,inputs,rows,probabilities,next_batch,written):
    indices=completed_indices(inputs,rows,next_batch);same(written,len(indices),'Completed batch row count')
    validate_probabilities(probabilities,indices)
    return dict(version=1,signature=signature,next_batch=next_batch,rows_written=written,
        sample_ix_sha256=head_probes.array_digest(rows.iloc[indices].sample_ix.to_numpy()),
        cache_ix_sha256=head_probes.array_digest(rows.iloc[indices].cache_ix.to_numpy()),
        completed_probability_sha256=probability_digests(probabilities,indices),
        portable_validation_sha256=data.digest(OUT/'portable-validation.json'))


def verify_progress(progress,signature,inputs,rows,probabilities):
    same(progress,progress_record(signature,inputs,rows,probabilities,progress['next_batch'],progress['rows_written']),
        'Completed probability rows/signature/prefix changed')
    return progress['next_batch'],progress['rows_written']


