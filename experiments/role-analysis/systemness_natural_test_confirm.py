def validate_layout(metadata,inputs,rows,tokens,ledger):
    require(len(ledger)==128 and len({entry['source_uid'] for entry in ledger})==128
        and all(entry['split']=='test' for entry in ledger),'Fixed128 test status ledger changed.')
    require(Counter(entry['status'] for entry in ledger).keys() <= {'prepared','quality-failed'},'Unknown quality status.')
    prepared={entry['source_uid']:entry for entry in ledger if entry['status']=='prepared'}
    require(len(inputs)==len(prepared)==len(tokens)
        and set(inputs.source_uid)==set(prepared) and inputs.source_uid.is_unique
        and inputs.prompt_ix.tolist()==list(range(len(inputs))),'Prepared native input/source identity changed.')
    require(np.array_equal(rows.index,np.arange(len(rows)))
        and np.array_equal(rows.cache_ix,np.arange(len(rows))) and rows.sample_ix.is_unique
        and set(rows.split)<= {'test'} and set(rows.wrapper)<= {'native'}
        and set(rows.role)==(set(OBSERVED_ROLES) if prepared else set())
        and set(rows.source_uid)==set(prepared) and (rows.group_id==rows.source_uid).all(),
        'Test row ownership/split/native S/U/A coverage changed.')
    require(not rows.duplicated(['prompt_ix','token_ix']).any()
        and set(rows.prompt_ix)==set(inputs.prompt_ix),'Test content positions are missing or repeated.')
    for entry in inputs.itertuples():
        source=prepared[entry.source_uid];group=rows[rows.prompt_ix==entry.prompt_ix]
        require(len(tokens[entry.prompt_ix])==entry.length and group.source_uid.eq(entry.source_uid).all()
            and group.token_ix.between(0,entry.length-1).all()
            and set(group.role)==set(OBSERVED_ROLES),'Per-transcript S/U/A token identity changed.')
        require(all(tokens[entry.prompt_ix][row.token_ix]==row.token_id for row in group.itertuples()),'Cached test token IDs changed.')
        for field in ['dataset','template_id','family_id','dependency_component_id','eligible_clean_test']:
            require(field in source and group[field].eq(source[field]).all() and getattr(entry,field)==source[field],
                'Per-source dependency/eligibility metadata changed: '+field)
    require(len({entry['family_id'] for entry in ledger})==32,'The fixed32 system wording families changed.')
    if prepared:
        families=pd.DataFrame(list(prepared.values())).groupby('family_id').dependency_component_id.nunique()
        require(families.eq(1).all(),'Shared system wording family was split across dependency components.')
    # The builder independently parses every native content position. This
    # runner rechecks that coverage proof and all hash-bound cache identities.
    require(metadata['coverage']['all_content_tokens_scored'] is True and metadata['coverage']['independent_native_labels_match'] is True,
        'Independent native all-content parser proof is missing.')
    same(metadata['gallery_source_uids'],gallery_ids(ledger),'Predeclared fixed gallery source IDs')
    require(metadata['fixed_roots']==128 and metadata['fixed_system_families']==32
        and metadata['dependency_components']==rows.dependency_component_id.nunique()
        and metadata['clean_dependency_components']==rows.loc[rows.eligible_clean_test.eq(True),'dependency_component_id'].nunique(),
        'Published effective dependency counts changed.')
    same(metadata['system_family_counts'],dict(fixed=32,all_prepared=int(rows.family_id.nunique()),
        clean_prepared=int(rows.loc[rows.eligible_clean_test.eq(True),'family_id'].nunique())),
        'Actual all/clean system wording family counts')


