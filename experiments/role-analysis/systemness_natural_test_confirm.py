def readout_snapshot():
    """Development-model metadata only. Does not inspect any C4 confirmation."""
    paths,thresholds,frozen=builder().frozen_snapshot()
    validate_frozen(paths,thresholds,frozen)
    return paths,thresholds,frozen


def validate_frozen(paths,thresholds,frozen):
    """Pure pre-reply guard, also called by the builder before text access."""
    require(set(paths)==set(thresholds)==set(frozen['models'])==set(NAMES)
        and frozen['primary_candidate']==PRIMARY_CANDIDATE and frozen['models'][PRIMARY]==PRIMARY_MODEL_SHA256
        and thresholds[PRIMARY]==PRIMARY_THRESHOLD and frozen['thresholds']==thresholds,
        'The fixed primary head128 model/threshold or four-model coverage changed.')
    require(all(np.isfinite(value) and 0<=value<=1.00001 for value in thresholds.values()),'Invalid frozen threshold.')


