def count_values(array):
    tp,fp,fn,tn,correct,total=np.moveaxis(array[...,:6],-1,0)
    divide=lambda a,b:np.divide(a,b,out=np.full_like(a,np.nan,dtype=float),where=b>0)
    recall=divide(tp,tp+fn);specificity=divide(tn,tn+fp)
    values=dict(system_precision=divide(tp,tp+fp),system_recall=recall,system_f1=divide(2*tp,2*tp+fp+fn),
        system_balanced_accuracy=(recall+specificity)/2,system_false_positive_rate=divide(fp,fp+tn),accuracy=divide(correct,total))
    for i,role in enumerate(OBSERVED_ROLES):
        a,b=array[...,6+2*i],array[...,7+2*i]
        values['role_recall_'+role]=np.divide(a,b,out=np.full_like(a,np.nan,dtype=float),where=b>0)
    return values


def bootstrap(counts):
    comparisons=[];intervals=[];component_frames=[]
    if counts.empty:return comparisons,intervals,pd.DataFrame()
    for pi,((stratum,dataset),group) in enumerate(counts.groupby(['stratum','dataset'],sort=True)):
        require(set(group.model)==set(NAMES) and not group.duplicated(['model','source_uid']).any(),
            'Missing model or duplicate source bootstrap counts.')
        source_ids=None
        for name in NAMES:
            frame=group[group.model==name].sort_values('source_uid')[['source_uid','family_id','dependency_component_id']].reset_index(drop=True)
            if source_ids is None:source_ids=frame
            require(frame.equals(source_ids),'Source membership/dependency mapping differs between paired models.')
        aggregate=group.groupby(['model','dependency_component_id'],as_index=False)[COUNT_FIELDS].sum()
        component_frames.append(aggregate.assign(stratum=stratum,dataset=dataset))
        arrays={};ids=None
        for name in NAMES:
            frame=aggregate[aggregate.model==name].sort_values('dependency_component_id')
            require(len(frame)>0 and not frame.dependency_component_id.duplicated().any(),'Missing paired dependency component.')
            if ids is None:ids=frame.dependency_component_id.tolist()
            same(frame.dependency_component_id.tolist(),ids,'Four-model component pairing')
            arrays[name]=frame[COUNT_FIELDS].to_numpy(dtype=np.float64)
        rng=np.random.RandomState(data.SEED+128432+pi);draw=rng.randint(len(ids),size=(BOOTSTRAPS,len(ids)))
        point={name:count_values(array.sum(0)) for name,array in arrays.items()}
        samples={name:count_values(array[draw].sum(1)) for name,array in arrays.items()}
        common=dict(stratum=stratum,dataset=dataset,source_roots=int(group.source_uid.nunique()),
            dependency_components=len(ids),system_families=int(group.family_id.nunique()),
            bootstrap_replicates=BOOTSTRAPS,resampling_unit='shared-family-and-assistant-repeat connected dependency component')
        def interval(values):
            defined=np.isfinite(values);count=int(defined.sum())
            reason='fewer_than_two_dependency_components' if len(ids)<2 else 'no_defined_bootstrap_replicates' if not count else None
            low,high=np.quantile(values[defined],[.025,.975]) if reason is None else (None,None)
            return dict(ci95_low=None if low is None else float(low),ci95_high=None if high is None else float(high),
                defined_bootstrap_replicates=count,ci_available=reason is None,ci_unavailable_reason=reason)
        def finite(value):return float(value) if np.isfinite(value) else None
        for name in NAMES:
            for metric,value in point[name].items():
                intervals.append(common|dict(model=name,metric=metric,value=finite(value))|interval(samples[name][metric]))
        for before,after in itertools.combinations(NAMES,2):
            for metric in point[before]:
                comparisons.append(common|dict(baseline_model=before,comparison_model=after,metric=metric,
                    baseline=finite(point[before][metric]),comparison=finite(point[after][metric]),
                    gain_percentage_points=finite(100*(point[after][metric]-point[before][metric])))
                    |interval(100*(samples[after][metric]-samples[before][metric])))
    return comparisons,intervals,pd.concat(component_frames,ignore_index=True) if component_frames else pd.DataFrame()


