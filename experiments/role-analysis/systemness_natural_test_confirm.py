def competing_processes(proc=Path('/proc')):
    names={'systemness_head_confirm.py','systemness_long_confirm.py','systemness_head_scan.py','systemness_head_extract.py',
        'systemness_head_probes.py','systemness_head_fusion.py','systemness_long_extract.py','systemness_recover_local_bank.py',
        'systemness_long_probes.py','systemness_paired_probes.py','systemness_attention_confirm.py','systemness_natural_recheck.py',
        'systemness_natural_test_confirm.py'}
    active=[]
    for entry in proc.iterdir():
        if not entry.name.isdigit() or int(entry.name)==os.getpid():continue
        try:args=(entry/'cmdline').read_bytes().split(b'\0')
        except (FileNotFoundError,PermissionError,ProcessLookupError):continue
        if any(Path(arg.decode(errors='replace')).name in names for arg in args if arg):active.append(int(entry.name))
    return active


def no_competing_jobs():require(not competing_processes(),'Another experiment remains active; natural test GPU inference is forbidden.')


@contextmanager
def run_lock():
    import fcntl
    OUT.mkdir(parents=True,exist_ok=True)
    with (OUT/'.run.lock').open('a') as stream:
        try:fcntl.flock(stream.fileno(),fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError as error:raise RuntimeError('Another natural-test run owns this output.') from error
        try:yield
        finally:fcntl.flock(stream.fileno(),fcntl.LOCK_UN)


def register_hooks(model,capture,handles):
    # Append after every successful registration so partial failures are cleaned.
    for name,spec in SPECS.items():
        layer=model.model.layers[spec['layer']]
        if spec['point']=='mid':
            def before(module,args,key=name):capture.legacy(key,args[0])
            handles.append(layer.post_attention_layernorm.register_forward_pre_hook(before))
        else:
            require(spec['point']=='attention','Unexpected legacy hook point.')
            def after(module,args,output,key=name):capture.legacy(key,output[0])
            handles.append(layer.self_attn.register_forward_hook(after))
    for layer in capture.layers:handles.append(model.model.layers[layer].self_attn.o_proj.register_forward_pre_hook(capture.head_hook(layer)))


