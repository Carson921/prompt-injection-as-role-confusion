def finite(value):return float(value) if np.isfinite(value) else None


def count_values(array):
    array=np.asarray(array,dtype=np.float64)
    tp,fp,fn,tn,correct,total=np.moveaxis(array[...,:6],-1,0)
    def divide(a,b):return np.divide(a,b,out=np.full_like(a,np.nan,dtype=np.float64),where=b>0)
    recall=divide(tp,tp+fn);specificity=divide(tn,tn+fp)
    values=dict(system_precision=divide(tp,tp+fp),system_recall=recall,
        system_f1=divide(2*tp,2*tp+fp+fn),system_balanced_accuracy=(recall+specificity)/2,
        system_false_positive_rate=divide(fp,fp+tn),accuracy=divide(correct,total))
    for index,role in enumerate(OBSERVED):values['role_recall_'+role]=divide(array[...,6+index*2],array[...,7+index*2])
    return values


def token_metrics(p,roles,threshold):
    require(np.isfinite(threshold) and 0<=threshold<=1.00001,'Invalid frozen threshold.')
    p=np.asarray(p);y=np.asarray([data.ROLES.index(role) for role in roles],dtype=np.int64)
    require(p.shape==(len(y),5) and np.isfinite(p).all() and (p>=0).all() and (p<=1.00001).all()
        and np.allclose(p.sum(1),1,atol=2e-5,rtol=0),'Invalid probability rows.')
    predicted=p.argmax(1);positive=y==0;detected=p[:,0]>=threshold
    confusion=np.bincount(5*y+predicted,minlength=25).reshape(5,5)
    vector=np.array([np.sum(positive&detected),np.sum(~positive&detected),np.sum(positive&~detected),
        np.sum(~positive&~detected),np.sum(y==predicted),len(y)]+[
        value for role in OBSERVED for value in (np.sum((y==data.ROLES.index(role))&(predicted==y)),np.sum(y==data.ROLES.index(role)))],dtype=np.int64)
    metrics={name:finite(value) for name,value in count_values(vector).items()}
    # Threshold-independent ranking statistics with exact tied-score groups.
    auc=ap=None;positive_count=int(positive.sum());negative_count=len(y)-positive_count
    if positive_count:
        order=np.argsort(-p[:,0],kind='stable');scores=p[order,0];truth=positive[order]
        ends=np.r_[np.flatnonzero(scores[1:]!=scores[:-1]),len(scores)-1]
        true_positives=np.cumsum(truth)[ends]
        ap=float(np.sum(np.diff(np.r_[0,true_positives])/positive_count*true_positives/(ends+1)))
        if negative_count:
            from scipy.stats import rankdata
            ranks=rankdata(p[:,0],method='average')
            auc=float((ranks[positive].sum()-positive_count*(positive_count+1)/2)/(positive_count*negative_count))
    support=confusion.sum(1);denominator=support+confusion.sum(0)
    f1=np.divide(2*confusion.diagonal(),denominator,out=np.zeros(5),where=denominator>0)
    recall={role:finite(confusion[i,i]/support[i]) if support[i] else None for i,role in enumerate(data.ROLES)}
    metrics.update(tokens=len(y),status='observed-SUA-only' if len(y) else 'no-observations',
        system_threshold=float(threshold),role_support={role:int(support[i]) for i,role in enumerate(data.ROLES)},
        recall=recall,confusion=confusion.tolist(),observed_roles=[r for r in data.ROLES if support[data.ROLES.index(r)]],
        five_class_argmax_accuracy=metrics['accuracy'],macro_f1=float(f1[support>0].mean()) if len(y) else None,
        nll=float(-np.log(np.clip(p[np.arange(len(y)),y],1e-15,1)).mean()) if len(y) else None,
        system_auroc=auc,system_average_precision=ap,
        system_confusion=dict(zip(['tp','fp','fn','tn'],map(int,vector[:4]))),
        system_detection_by_role={role:float(detected[y==i].mean()) if support[i] else None for i,role in enumerate(data.ROLES)},
        cot_tool_recall_status='N/A: zero observed truth support')
    return metrics,vector,predicted,detected


def summarize(rows,physical,thresholds):
    require(set(physical)==set(PHYSICAL) and set(thresholds)==set(RECORDS),'Physical/record coverage changed.')
    require(rows.index.tolist()==list(range(len(rows))) and rows.cache_ix.tolist()==list(range(len(rows)))
        and set(rows.role)<=set(OBSERVED),'Natural row index/role identity changed.')
    for p in physical.values():require(p.shape==(len(rows),5),'Physical probability row count differs.')
    metrics=[];counts=[];messages=[]
    for stratum,dataset in STRATA:
        subset=rows if stratum=='all-prepared' else rows[rows.eligible_clean_test.eq(True)]
        group=subset if dataset=='all' else subset[subset.dataset.eq(dataset)]
        for record in RECORDS:
            p=physical[closed.RECORD_TO_MODEL[record]];values=p[group.index.to_numpy(dtype=np.int64)]
            result,_,predicted,detected=token_metrics(values,group.role.tolist(),thresholds[record])
            common=dict(stratum=stratum,dataset=dataset,model=record,physical_model=closed.RECORD_TO_MODEL[record],
                source_roots=int(group.source_uid.nunique()),system_families=int(group.family_id.nunique()),
                dependency_components=int(group.dependency_component_id.nunique()))
            metrics.append(dict(common,**result))
            if group.empty:continue
            frame=group[['source_uid','family_id','dependency_component_id']].copy();truth=group.role.eq('system').to_numpy()
            y=group.role.map({role:i for i,role in enumerate(data.ROLES)}).to_numpy(dtype=np.int64)
            for key,value in dict(tp=truth&detected,fp=~truth&detected,fn=truth&~detected,tn=~truth&~detected,
                correct=predicted==y,tokens=np.ones(len(y),np.int64)).items():frame[key]=value
            for role in OBSERVED:
                observed=group.role.eq(role).to_numpy();frame[role+'_correct']=observed&(predicted==data.ROLES.index(role));frame[role+'_tokens']=observed
            counts.append(frame.groupby(['source_uid','family_id','dependency_component_id'],as_index=False)[COUNT_FIELDS].sum()
                .assign(stratum=stratum,dataset=dataset,model=record))
            # One projection per record/stratum; no pooled/source double counting.
            if dataset=='all':
                projection=group[['source_uid','message_ix','role','family_id','dependency_component_id']].copy()
                for i,role in enumerate(data.ROLES):projection['p_'+role]=values[:,i]
                messages.append(projection.groupby(['source_uid','message_ix','role','family_id','dependency_component_id'],as_index=False)
                    .agg(**{'p_'+role:('p_'+role,'mean') for role in data.ROLES},tokens=('p_system','size')).assign(stratum=stratum,model=record))
    for stratum,dataset in STRATA:
        before=next(r for r in metrics if r['stratum']==stratum and r['dataset']==dataset and r['model']=='old-head-maximin')
        after=next(r for r in metrics if r['stratum']==stratum and r['dataset']==dataset and r['model']=='old-head-original')
        for field in ['accuracy','five_class_argmax_accuracy','macro_f1','nll','confusion','recall','role_support',
            'system_auroc','system_average_precision']:
            require(before[field]==after[field],'Old-head threshold aliases changed probability/argmax/AUC/AP evidence: '+field)
    count_columns=['source_uid','family_id','dependency_component_id']+COUNT_FIELDS+['stratum','dataset','model']
    message_columns=['source_uid','message_ix','role','family_id','dependency_component_id']+[
        'p_'+role for role in data.ROLES]+['tokens','stratum','model']
    return metrics,pd.concat(counts,ignore_index=True) if counts else pd.DataFrame(columns=count_columns),pd.concat(messages,ignore_index=True) if messages else pd.DataFrame(columns=message_columns)


def bootstrap(counts):
    comparisons=[];intervals=[];components=[]
    for stratum_index,(stratum,dataset) in enumerate(STRATA):
        group=counts[(counts.stratum==stratum)&(counts.dataset==dataset)]
        source_ids=None;arrays={};ids=[]
        for record in RECORDS:
            frame=group[group.model==record]
            require(not frame.source_uid.duplicated().any(),'A paired source is duplicated.')
            metadata=frame[['source_uid','family_id','dependency_component_id']].sort_values('source_uid').reset_index(drop=True)
            if source_ids is None:source_ids=metadata
            require(metadata.equals(source_ids),'Four records do not share source/component membership.')
            aggregate=frame.groupby('dependency_component_id',as_index=False)[COUNT_FIELDS].sum().sort_values('dependency_component_id')
            if not arrays:ids=aggregate.dependency_component_id.tolist()
            require(aggregate.dependency_component_id.tolist()==ids,'Four records do not share paired component IDs.')
            arrays[record]=aggregate[COUNT_FIELDS].to_numpy(dtype=np.float64)
            components.append(aggregate.assign(stratum=stratum,dataset=dataset,model=record))
        rng=np.random.RandomState(BOOTSTRAP_SEED+stratum_index)
        draw=rng.randint(len(ids),size=(BOOTSTRAPS,len(ids))) if ids else np.empty((BOOTSTRAPS,0),np.int64)
        points={record:count_values(array.sum(0)) for record,array in arrays.items()}
        samples={record:count_values(array[draw].sum(1)) for record,array in arrays.items()}
        common=dict(stratum=stratum,dataset=dataset,source_roots=len(source_ids),
            dependency_components=len(ids),system_families=int(group.family_id.nunique()),
            bootstrap_replicates=BOOTSTRAPS,resampling_unit='shared-family-and-assistant-repeat connected component')
        def interval(values):
            defined=np.isfinite(values);count=int(defined.sum())
            reason='fewer_than_two_dependency_components' if len(ids)<2 else 'no_defined_bootstrap_replicates' if not count else None
            low,high=np.quantile(values[defined],[.025,.975]) if reason is None else (None,None)
            return dict(ci95_low=None if low is None else float(low),ci95_high=None if high is None else float(high),
                defined_bootstrap_replicates=count,undefined_bootstrap_replicates=BOOTSTRAPS-count,
                ci_available=reason is None,ci_unavailable_reason=reason)
        for record in RECORDS:
            for statistic in STATISTICS:intervals.append(dict(common,model=record,metric=statistic,
                value=finite(points[record][statistic]),**interval(samples[record][statistic])))
        for before,after in itertools.combinations(RECORDS,2):
            for statistic in STATISTICS:
                comparisons.append(dict(common,baseline_model=before,comparison_model=after,metric=statistic,
                    baseline=finite(points[before][statistic]),comparison=finite(points[after][statistic]),
                    gain_percentage_points=finite(100*(points[after][statistic]-points[before][statistic])),
                    **interval(100*(samples[after][statistic]-samples[before][statistic]))))
    require(len(intervals)==216 and len(comparisons)==324,'Fixed bootstrap reporting coverage changed.')
    return comparisons,intervals,pd.concat(components,ignore_index=True)


